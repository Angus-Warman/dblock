package tests

import (
	"testing"

	"github.com/google/uuid"
	"github.com/stretchr/testify/require"
)

func TestIntegerPrimaryKeyAutoRowID(t *testing.T) {
	db := openDB(t)
	assertExec(t, db, "CREATE TABLE foo (id INTEGER PRIMARY KEY, value TEXT)")
	assertExec(t, db, "INSERT INTO foo (value) VALUES ('first')")
	assertExec(t, db, "INSERT INTO foo (value) VALUES ('second')")
	assertQueryRows(t, db, "SELECT id, value FROM foo", [][]any{
		{int64(1), "first"},
		{int64(2), "second"},
	})
}

